<?php
/**
 * Jetpack Forms integration adapter.
 *
 * @package AB_Form_Entries_Manager
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Class ABFEM_Jetpack_Forms
 */
class ABFEM_Jetpack_Forms extends ABFEM_Base_Integration {

	/**
	 * Track handled post IDs within single request to avoid duplicate triggers.
	 *
	 * @var array
	 */
	private $handled_posts = array();

	/**
	 * Unique identifier.
	 *
	 * @return string
	 */
	public function get_id() {
		return 'jetpack';
	}

	/**
	 * Display name.
	 *
	 * @return string
	 */
	public function get_name() {
		return 'Jetpack Forms';
	}

	/**
	 * Check if installed.
	 *
	 * @return bool
	 */
	public function is_installed() {
		return $this->plugin_file_exists( 'jetpack/jetpack.php' );
	}

	/**
	 * Check if active.
	 *
	 * @return bool
	 */
	public function is_active() {
		return defined( 'JETPACK__VERSION' ) || class_exists( 'Grunion_Contact_Form' ) || class_exists( '\Automattic\Jetpack\Forms\Jetpack_Forms' );
	}

	/**
	 * Get version.
	 *
	 * @return string
	 */
	public function get_version() {
		if ( defined( 'JETPACK__VERSION' ) ) {
			return JETPACK__VERSION;
		}
		return $this->get_version_from_file( 'jetpack/jetpack.php' );
	}

	/**
	 * Short description.
	 *
	 * @return string
	 */
	public function get_description() {
		return __( 'Captures submissions generated by Jetpack contact forms and feedback blocks.', 'ab-form-entries-manager' );
	}

	/**
	 * Notes.
	 *
	 * @return string
	 */
	public function get_notes() {
		return __( 'Hooks into the official "grunion_after_feedback_post_inserted" and "grunion_pre_message_sent" actions.', 'ab-form-entries-manager' );
	}

	/**
	 * Initialize hooks.
	 */
	public function init() {
		if ( ! $this->is_active() ) {
			return;
		}

		add_action( 'grunion_after_feedback_post_inserted', array( $this, 'handle_submission' ), 10, 4 );
		add_action( 'grunion_pre_message_sent', array( $this, 'handle_pre_message' ), 10, 3 );
	}

	/**
	 * Handle Jetpack submission on feedback post insert.
	 *
	 * @param int   $post_id      Feedback post ID.
	 * @param array $fields       Form fields metadata.
	 * @param bool  $is_spam      Spam status.
	 * @param array $entry_values Normalized entry values.
	 */
	public function handle_submission( $post_id, $fields = array(), $is_spam = false, $entry_values = array() ) {
		if ( in_array( $post_id, $this->handled_posts, true ) ) {
			return;
		}
		$this->handled_posts[] = $post_id;

		$parent_id  = wp_get_post_parent_id( $post_id );
		$form_title = $parent_id ? get_the_title( $parent_id ) : __( 'Jetpack Form', 'ab-form-entries-manager' );
		$source_url = $parent_id ? get_permalink( $parent_id ) : '';

		$normalized_fields = array();
		$submitter_name    = '';
		$submitter_email   = '';

		// Use $entry_values if available, or extract from $fields.
		$source_data = ! empty( $entry_values ) && is_array( $entry_values ) ? $entry_values : ( is_array( $fields ) ? $fields : array() );

		foreach ( $source_data as $key => $val ) {
			/* translators: %s: Field key/index */
			$label = is_string( $key ) ? ucwords( str_replace( array( '-', '_' ), ' ', $key ) ) : sprintf( __( 'Field %s', 'ab-form-entries-manager' ), $key );
			$value = $val;
			$type  = $this->detect_field_type( (string) $key, $value );

			if ( is_array( $val ) && isset( $val['value'] ) ) {
				$value = $val['value'];
				$label = ! empty( $val['label'] ) ? $val['label'] : $label;
				$type  = ! empty( $val['type'] ) ? $val['type'] : $type;
			}

			if ( empty( $submitter_email ) && ( 'email' === $type || false !== stripos( (string) $key, 'email' ) ) ) {
				if ( is_string( $value ) && is_email( $value ) ) {
					$submitter_email = $value;
				}
			}

			if ( empty( $submitter_name ) && ( 'name' === $type || false !== stripos( (string) $key, 'name' ) ) ) {
				if ( is_string( $value ) && ! empty( $value ) && ! is_email( $value ) ) {
					$submitter_name = $value;
				}
			}

			$normalized_fields[] = array(
				'name'  => (string) $key,
				'label' => $label,
				'type'  => $type,
				'value' => $value,
			);
		}

		$payload = array(
			'source_form_id'   => (string) ( $parent_id ?: $post_id ),
			'source_form_name' => $form_title,
			'source_entry_id'  => (string) $post_id,
			'source_url'       => $source_url,
			'submitter_name'   => $submitter_name,
			'submitter_email'  => $submitter_email,
			'fields'           => $normalized_fields,
		);

		$this->record_submission( $payload );
	}

	/**
	 * Fallback handler for grunion_pre_message_sent.
	 *
	 * @param int   $post_id      Feedback post ID.
	 * @param array $all_values   Parsed form values.
	 * @param array $extra_values Additional metadata.
	 */
	public function handle_pre_message( $post_id, $all_values = array(), $extra_values = array() ) {
		if ( in_array( $post_id, $this->handled_posts, true ) ) {
			return;
		}

		$this->handle_submission( $post_id, array(), false, $all_values );
	}

	/**
	 * Retrieve all discovered forms.
	 *
	 * @return array
	 */
	public function get_forms() {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
		$results = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT DISTINCT pm_id.meta_value AS id, pm_name.meta_value AS name
				 FROM {$wpdb->posts} p
				 INNER JOIN {$wpdb->postmeta} pm_plugin ON p.ID = pm_plugin.post_id AND pm_plugin.meta_key = '_abfem_source_plugin' AND pm_plugin.meta_value = 'jetpack'
				 INNER JOIN {$wpdb->postmeta} pm_id ON p.ID = pm_id.post_id AND pm_id.meta_key = '_abfem_form_id'
				 LEFT JOIN {$wpdb->postmeta} pm_name ON p.ID = pm_name.post_id AND pm_name.meta_key = '_abfem_form_name'
				 WHERE p.post_type = %s",
				ABFEM_POST_TYPE
			),
			ARRAY_A
		);

		return is_array( $results ) ? $results : array();
	}
}
